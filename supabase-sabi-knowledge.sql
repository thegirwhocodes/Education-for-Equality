CREATE TABLE IF NOT EXISTS sabi_knowledge_artifacts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  path TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  domain TEXT NOT NULL DEFAULT '',
  format TEXT NOT NULL DEFAULT '',
  sha TEXT,
  byte_size INTEGER NOT NULL DEFAULT 0,
  purpose TEXT NOT NULL DEFAULT '',
  last_reviewed_at DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sabi_knowledge_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT UNIQUE,
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  summary TEXT NOT NULL DEFAULT '',
  why_it_matters TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active',
  confidence TEXT NOT NULL DEFAULT 'medium',
  origin_session_id TEXT,
  origin_commit_sha TEXT,
  decision_date DATE,
  decision_maker TEXT,
  domain TEXT NOT NULL DEFAULT '',
  caution TEXT NOT NULL DEFAULT '',
  used_in TEXT NOT NULL DEFAULT '',
  implements_path TEXT NOT NULL DEFAULT '',
  product_area TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sabi_knowledge_items_type_chk CHECK (type IN (
    'problem','need','evidence','insight','assumption','decision','principle',
    'requirement','design','implementation','experiment','outcome','claim'
  )),
  CONSTRAINT sabi_knowledge_items_status_chk CHECK (status IN (
    'proposed','active','experimental','validated','unvalidated','rejected',
    'superseded','deprecated','dormant'
  )),
  CONSTRAINT sabi_knowledge_items_confidence_chk CHECK (confidence IN ('high','medium','low'))
);

CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_items_type ON sabi_knowledge_items (type);
CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_items_domain ON sabi_knowledge_items (domain);
CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_items_status ON sabi_knowledge_items (status);

CREATE TABLE IF NOT EXISTS sabi_knowledge_relationships (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  from_id UUID NOT NULL REFERENCES sabi_knowledge_items(id) ON DELETE CASCADE,
  to_id UUID NOT NULL REFERENCES sabi_knowledge_items(id) ON DELETE CASCADE,
  rel TEXT NOT NULL,
  confidence TEXT NOT NULL DEFAULT 'medium',
  status TEXT NOT NULL DEFAULT 'verified',
  origin_session_id TEXT,
  origin_commit_sha TEXT,
  verified_by TEXT,
  verified_at TIMESTAMPTZ,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sabi_knowledge_rel_chk CHECK (rel IN (
    'supported_by','contradicted_by','derived_from','informed','caused','requires',
    'implements','validates','tested_by','produced','supersedes','depends_on',
    'part_of','used_in','owned_by','challenges'
  )),
  CONSTRAINT sabi_knowledge_rel_status_chk CHECK (status IN ('candidate','verified','rejected')),
  CONSTRAINT sabi_knowledge_rel_conf_chk CHECK (confidence IN ('high','medium','low')),
  UNIQUE (from_id, to_id, rel)
);

CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_rel_from ON sabi_knowledge_relationships (from_id);
CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_rel_to ON sabi_knowledge_relationships (to_id);
CREATE INDEX IF NOT EXISTS idx_sabi_knowledge_rel_status ON sabi_knowledge_relationships (status);

CREATE TABLE IF NOT EXISTS sabi_knowledge_verifications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  relationship_id UUID NOT NULL REFERENCES sabi_knowledge_relationships(id) ON DELETE CASCADE,
  action TEXT NOT NULL,
  reviewer TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sabi_knowledge_ver_action_chk CHECK (action IN ('accept','reject','edit'))
);

CREATE TABLE IF NOT EXISTS sabi_work_projects (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Active',
  owner_id UUID REFERENCES sabi_work_people(id) ON DELETE SET NULL,
  linked_knowledge_id UUID REFERENCES sabi_knowledge_items(id) ON DELETE SET NULL,
  summary TEXT NOT NULL DEFAULT '',
  created_from TEXT NOT NULL DEFAULT 'manual',
  due_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sabi_work_projects_from_chk CHECK (created_from IN ('manual','insight'))
);

CREATE INDEX IF NOT EXISTS idx_sabi_work_projects_status ON sabi_work_projects (status);

CREATE TABLE IF NOT EXISTS sabi_company_partners (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'other',
  status TEXT NOT NULL DEFAULT 'active',
  notes TEXT NOT NULL DEFAULT '',
  linked_knowledge_id UUID REFERENCES sabi_knowledge_items(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT sabi_company_partners_kind_chk CHECK (kind IN (
    'telco','ngo','school','government','fund','other'
  ))
);

ALTER TABLE sabi_work_tasks ADD COLUMN IF NOT EXISTS project_id UUID REFERENCES sabi_work_projects(id) ON DELETE SET NULL;
ALTER TABLE sabi_work_tasks ADD COLUMN IF NOT EXISTS linked_knowledge_id UUID REFERENCES sabi_knowledge_items(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_sabi_work_tasks_project ON sabi_work_tasks (project_id);

